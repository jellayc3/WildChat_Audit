os.makedirs(os.path.join(OUT, "figures"), exist_ok=True)

POOL_CONVS, POOL_OPENERS, POOL_PCT = "2,808,223", "631", "44.4"   # stage1_frames/build_poolscreen.py

def rd(name): return pd.read_csv(os.path.join(F, name) if name.startswith("f") else os.path.join(OUTPUT, name))
def num(x, nd=2, sign=False):
    if pd.isna(x): return "--"
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return "$" + s + "$" if s.startswith("-") else s
def ci(lo, hi, nd=2): return f"[{num(lo, nd)}, {num(hi, nd)}]"
def pv(p):
    if pd.isna(p): return "--"
    return "$<$.001" if p < .001 else f"{p:.3f}".lstrip("0")
def i(x): return f"{int(round(x)):,}"
def esc(s): return str(s).replace("Event sample", "Supporting sample").replace("event sample", "supporting sample").replace("_", r"\_").replace("&", r"\&").replace("%", r"\%").replace(">=", "$\\geq$").replace("<", "$<$").replace(">", "$>$")

L = []
def p(s=""): L.append(s)
def table(caption, label, header, rows, spec=None, note=None):
    spec = spec or ("l" + "r" * (len(header) - 1))
    p(r"\begin{table}[h]"); p(r"\caption{" + caption + "}"); p(r"\label{" + label + "}"); p(r"\footnotesize"); p(r"\setlength{\tabcolsep}{4pt}")
    p(r"\begin{adjustbox}{max width=\linewidth}"); p(r"\begin{tabular}{@{}" + spec + "@{}}"); p(r"\toprule"); p(" & ".join(header) + r" \\"); p(r"\midrule")
    for r in rows: p(r"\midrule" if r == "MID" else " & ".join(str(c) for c in r) + r" \\")
    p(r"\bottomrule"); p(r"\end{tabular}"); p(r"\end{adjustbox}")
    if note: p(r"\par\smallskip\footnotesize " + note)
    p(r"\end{table}"); p()
def figure(src, name, caption, label):
    shutil.copy(src, os.path.join(OUT, "figures", name))
    p(r"\begin{figure}[h]"); p(r"\centering"); p(r"\includegraphics[width=\linewidth]{figures/" + name + "}")
    p(r"\caption{" + caption + "}"); p(r"\label{" + label + "}"); p(r"\end{figure}"); p()

CRIT_NAMES = {"Agree": "Agreement", "Disagree": "Disagreement", "Flatter": "Flattery"}
