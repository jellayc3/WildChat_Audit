#!/usr/bin/env python3
"""Build the paper's appendix (appendix.tex + figures) from the pipeline outputs.

    python tools/build_appendix.py <out_dir>

Every number in the appendix is read from output/ at build time; nothing is typed in by
hand except the pool-screen totals, which come from data not distributed with this package
(see stage1_frames/build_poolscreen.py). Run after ./run_all.sh.
Writes <out_dir>/appendix.tex and <out_dir>/figures/appendix_*.png.
"""
